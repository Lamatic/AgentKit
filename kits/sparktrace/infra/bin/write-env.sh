#!/usr/bin/env bash
# Pull stack outputs and write the AWS block into the app's .env.local,
# PRESERVING every existing line (Lamatic keys etc.) — only the AWS/Athena/Glue
# keys we manage are replaced. Never printed to stdout (contains a secret key).
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

require_aws
[ "$(stack_status)" != "DOES_NOT_EXIST" ] || die "stack '$STACK_NAME' not found — run up.sh first."

REGION_OUT="$(stack_output AwsRegion)";        REGION_OUT="${REGION_OUT:-$AWS_REGION}"
WG="$(stack_output WorkGroupName)"
OUTLOC="$(stack_output AthenaOutputLocation)"
GLUEDB="$(stack_output GlueDatabase)"
KEY_ID="$(stack_output AppAccessKeyId)"
KEY_SECRET="$(stack_output AppSecretAccessKey)"

# Decide the credential source the APP uses, and emit a COMPLETE set so the AWS
# SDK's default chain can't silently resolve a different identity for
# Athena/Glue/S3:
#   1. dedicated read-only app user (CREATE_APP_USER=true) -> its static key.
#   2. fallback: mirror the deployer's own source — a named profile, or the full
#      static triplet including a session token for temporary credentials.
CRED_LINES=""
if [ -n "$KEY_ID" ] && [ "$KEY_ID" != "None" ]; then
  CRED_LINES="AWS_ACCESS_KEY_ID=$KEY_ID
AWS_SECRET_ACCESS_KEY=$KEY_SECRET"
elif [ -n "${AWS_PROFILE:-}" ]; then
  warn "No app IAM user in stack — app will use the deployer AWS_PROFILE '$AWS_PROFILE'."
  CRED_LINES="AWS_PROFILE=$AWS_PROFILE"
elif [ -n "${AWS_ACCESS_KEY_ID:-}" ] && [ -n "${AWS_SECRET_ACCESS_KEY:-}" ]; then
  warn "No app IAM user in stack — using the deployer static credentials."
  CRED_LINES="AWS_ACCESS_KEY_ID=$AWS_ACCESS_KEY_ID
AWS_SECRET_ACCESS_KEY=$AWS_SECRET_ACCESS_KEY"
  [ -n "${AWS_SESSION_TOKEN:-}" ] && CRED_LINES="$CRED_LINES
AWS_SESSION_TOKEN=$AWS_SESSION_TOKEN"
else
  die "No app credentials available. Set CREATE_APP_USER=true, or provide AWS_PROFILE or AWS_ACCESS_KEY_ID/AWS_SECRET_ACCESS_KEY in infra/.env."
fi

# Keys this script owns (stripped from the existing file before re-adding) so a
# stale credential from a previous run never lingers.
MANAGED='^(AWS_ACCESS_KEY_ID|AWS_SECRET_ACCESS_KEY|AWS_SESSION_TOKEN|AWS_PROFILE|AWS_REGION|ATHENA_WORKGROUP|ATHENA_OUTPUT_LOCATION|GLUE_DATABASE)='

mkdir -p "$(dirname "$APP_ENV")"
tmp="$(mktemp)"
# keep every existing non-managed line (Lamatic keys, comments, etc.)
if [ -f "$APP_ENV" ]; then grep -vE "$MANAGED" "$APP_ENV" > "$tmp" || true; fi

{
  echo ""
  echo "# --- SparkTrace live AWS backend (generated by infra/bin/write-env.sh) ---"
  printf '%s\n' "$CRED_LINES"
  echo "AWS_REGION=$REGION_OUT"
  echo "ATHENA_WORKGROUP=$WG"
  echo "ATHENA_OUTPUT_LOCATION=$OUTLOC"
  echo "GLUE_DATABASE=$GLUEDB"
} >> "$tmp"

mv "$tmp" "$APP_ENV"
ok "Wrote AWS block to $APP_ENV (existing keys preserved). File is gitignored."
