#!/usr/bin/env bash
# Pull stack outputs and write the AWS block into the app's .env.local,
# PRESERVING every existing line (Lamatic keys etc.) — only the AWS/Athena/Glue
# keys we manage are replaced. Never printed to stdout (contains a secret key).
set -euo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

require_aws
[ "$(stack_status)" != "DOES_NOT_EXIST" ] || die "stack '$STACK_NAME' not found — run up.sh first."

REGION_OUT="$(stack_output AwsRegion)";        REGION_OUT="${REGION_OUT:-$AWS_REGION}"
WG="$(stack_output WorkGroupName)"
OUTLOC="$(stack_output AthenaOutputLocation)"
GLUEDB="$(stack_output GlueDatabase)"
KEY_ID="$(stack_output AppAccessKeyId)"
KEY_SECRET="$(stack_output AppSecretAccessKey)"

# If no dedicated app user was created, fall back to the deployer creds.
if [ -z "$KEY_ID" ] || [ "$KEY_ID" = "None" ]; then
  KEY_ID="${AWS_ACCESS_KEY_ID:-}"
  KEY_SECRET="${AWS_SECRET_ACCESS_KEY:-}"
  warn "No app IAM user in stack — using deployer credentials in .env.local (set CREATE_APP_USER=true for least-privilege)."
fi

MANAGED='^(AWS_ACCESS_KEY_ID|AWS_SECRET_ACCESS_KEY|AWS_SESSION_TOKEN|AWS_REGION|ATHENA_WORKGROUP|ATHENA_OUTPUT_LOCATION|GLUE_DATABASE)='

mkdir -p "$(dirname "$APP_ENV")"
tmp="$(mktemp)"
# keep every existing non-managed line (Lamatic keys, comments, etc.)
if [ -f "$APP_ENV" ]; then grep -vE "$MANAGED" "$APP_ENV" > "$tmp" || true; fi

{
  echo ""
  echo "# --- SparkTrace live AWS backend (generated by infra/scripts/write-env.sh) ---"
  echo "AWS_ACCESS_KEY_ID=$KEY_ID"
  echo "AWS_SECRET_ACCESS_KEY=$KEY_SECRET"
  echo "AWS_REGION=$REGION_OUT"
  echo "ATHENA_WORKGROUP=$WG"
  echo "ATHENA_OUTPUT_LOCATION=$OUTLOC"
  echo "GLUE_DATABASE=$GLUEDB"
} >> "$tmp"

mv "$tmp" "$APP_ENV"
ok "Wrote AWS block to $APP_ENV (existing keys preserved). File is gitignored."
